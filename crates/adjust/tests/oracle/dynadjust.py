#!/usr/bin/env python3
"""Run DynAdjust on the adjust crate's oracle networks and store its results.

DynAdjust is Geoscience Australia's least squares adjustment
(https://github.com/icsm-au/DynAdjust, Apache-2.0). The networks are defined
in `tests/dynadjust.rs`; its ignored `write_dynaml` test writes them as
DynaML. This script runs DynAdjust on each and writes the results that
`matches_dynadjust` compares against to `tests/data/dynadjust/<name>.csv`.
Each file's first line records the DynAdjust version and options. Re-run
this after changing the networks or DynAdjust's version and review the diff.

Building DynAdjust on Ubuntu 24.04 (v1.4.1 was used):

    apt-get install libxerces-c-dev xsdcxx libboost-system-dev \\
        libboost-filesystem-dev libboost-timer-dev libboost-thread-dev \\
        libboost-program-options-dev libopenblas-dev liblapacke-dev
    git clone --depth 1 --branch v1.4.1 https://github.com/icsm-au/DynAdjust.git
    cmake -S DynAdjust/dynadjust -B build -DCMAKE_BUILD_TYPE=Release
    cmake --build build --parallel 4

Then, from anywhere in the repository:

    python3 -I crates/adjust/tests/oracle/dynadjust.py DynAdjust/bin

DynAdjust gives every free station a weak a priori constraint; it's set to
1 km here, so it changes nothing at the precision compared. It rewrites its
binary files as it adjusts, so each network is imported afresh.
"""

import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent.parent
DATA = CRATE / "tests" / "data" / "dynadjust"
NETWORKS = ["clusters", "baselines", "larger"]
ADJUST_OPTIONS = [
    "--simultaneous-adjustment",
    "--output-adj-msr",
    "--output-pos-uncertainty",
    "--output-json",
    "--free-stn-sd",
    "1000",
    "--max-iterations",
    "20",
]


def write_dynaml(work):
    # The test reads its results at compile time, so they must exist first.
    DATA.mkdir(parents=True, exist_ok=True)
    for name in NETWORKS:
        (DATA / f"{name}.csv").touch(exist_ok=True)
    env = dict(os.environ, GNSS_DYNAML_DIR=str(work))
    subprocess.run(
        ["cargo", "test", "--quiet", "-p", "gnss-adjust", "--test", "dynadjust",
         "write_dynaml", "--", "--ignored"],
        cwd=CRATE, env=env, check=True,
    )


def records(path):
    with open(path) as f:
        for line in f:
            yield json.loads(line)


def as_list(value):
    return value if isinstance(value, list) else [value]


def run(binaries, work, name):
    for suffix in [".bst", ".bms", ".aml", ".asl", ".map", ".dbid", ".imp"]:
        (work / f"{name}{suffix}").unlink(missing_ok=True)
    subprocess.run(
        [str(binaries / "dnaimport"), "-n", name, f"{name}stn.xml", f"{name}msr.xml"],
        cwd=work, check=True, stdout=subprocess.DEVNULL,
    )
    subprocess.run(
        [str(binaries / "dnaadjust"), name] + ADJUST_OPTIONS,
        cwd=work, check=True, stdout=subprocess.DEVNULL,
    )
    software = None
    statistics = None
    measurements = []
    for record in records(work / f"{name}.simult.adj.jsonl"):
        if "DnaAdjustmentReport" in record:
            software = record["DnaAdjustmentReport"]["software"]
        elif "DnaStatistics" in record:
            statistics = record["DnaStatistics"]
        elif "DnaMeasurement" in record:
            measurements.append(record["DnaMeasurement"])
    stations = [r["DnaStation"] for r in records(work / f"{name}.simult.xyz.jsonl") if "DnaStation" in r]
    return software, statistics, measurements, stations


def describe(binaries):
    try:
        return subprocess.run(
            ["git", "-C", str(binaries.parent), "describe", "--tags", "--always"],
            capture_output=True, text=True, check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main():
    binaries = Path(sys.argv[1]).resolve()
    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)
        write_dynaml(work)
        for name in NETWORKS:
            software, statistics, measurements, stations = run(binaries, work, name)
            lines = [
                f"# Generated by tests/oracle/dynadjust.py with {software} ({describe(binaries)}): "
                f"dnaadjust {' '.join(ADJUST_OPTIONS)}",
                f"statistics,{statistics['chisq']!r},{statistics['dof']},"
                f"{statistics['sigma_zero']!r},{statistics['chisq_lower']!r},"
                f"{statistics['chisq_upper']!r}",
            ]
            for s in stations:
                adjusted = s["Adjusted"]
                u = s.get("Uncertainty", {})
                lines.append(
                    f"station,{s['Name']},{adjusted['X']!r},{adjusted['Y']!r},{adjusted['Z']!r},"
                    f"{u.get('HzPosU', 0.0)!r},{u.get('VtPosU', 0.0)!r}"
                )
            for index, m in enumerate(measurements):
                parts = m.get("GPSBaseline") or m.get("Clusterpoint")
                for element, (part, nstat) in enumerate(zip(as_list(parts), as_list(m["NStat"]))):
                    lines.append(
                        f"nstat,{index},{element},{part['First']},{part.get('Second', '')},"
                        f"{nstat['X']!r},{nstat['Y']!r},{nstat['Z']!r}"
                    )
            (DATA / f"{name}.csv").write_text("\n".join(lines) + "\n")
            print(f"{name}: {len(stations)} stations, {len(measurements)} measurements, "
                  f"sigma zero {statistics['sigma_zero']:.4f}")


if __name__ == "__main__":
    main()
