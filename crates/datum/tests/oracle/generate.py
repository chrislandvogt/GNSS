#!/usr/bin/env python3
"""Generate the reference data that the datum crate's tests compare against.

Reference values come from two independent implementations:

- PROJ, through pyproj, using the EPSG parameters in PROJ's database.
- GeodePy, Geoscience Australia's Python geodesy package.

Each output file's first line records the versions used. Re-run this after
changing either version and review the diff: any change in a reference value
needs explaining.

    python3 -m venv .venv
    .venv/bin/pip install geodepy==0.7.0 pyproj==3.8.0 numpy==2.2.6

GeodePy 0.7.0's covariance propagation fails with NumPy 2.5 and later, so NumPy is pinned.
    .venv/bin/python -I generate.py

PROJ runs with network access off, so no grids are involved: these are the
analytic transformations and projections only.
"""

import copy
import math
from importlib.metadata import version
from pathlib import Path

import geodepy
import numpy as np
import pyproj
from geodepy.constants import (
    Transformation,
    TransformationSD,
    gda94_to_gda2020,
    itrf2014_to_gda2020,
    itrf2020_to_itrf2014,
)
from geodepy.convert import geo2grid
from geodepy.transform import conform7

pyproj.network.set_network_enabled(False)

OUT = Path(__file__).resolve().parent.parent / "data"
EPOCHS = [1994.0, 2005.5, 2010.0, 2018.0, 2024.75, 2031.0]


def versions():
    return (
        f"# Generated by tests/oracle/generate.py with GeodePy {version('geodepy')}, "
        f"NumPy {np.__version__}, pyproj {pyproj.__version__}, PROJ {pyproj.proj_version_str}, "
        f"EPSG database {pyproj.database.get_database_metadata('EPSG.VERSION')}\n"
    )


def points():
    """A grid over Australia at a range of heights, plus the offshore territories."""
    pts = []
    heights = [-35.0, 120.5, 650.0, 2228.0]
    k = 0
    for i in range(9):
        for j in range(9):
            lat = -10.0 - 4.25 * i
            lon = 113.0 + 5.0 * j + 0.37 * (k % 3)
            pts.append((lat, lon, heights[k % 4]))
            k += 1
    pts += [
        (-10.49, 105.69, 250.0),  # Christmas Island
        (-12.19, 96.83, 3.0),  # Cocos (Keeling) Islands
        (-29.04, 167.95, 100.0),  # Norfolk Island
        (-31.55, 159.08, 50.0),  # Lord Howe Island
        (-54.5, 158.94, 6.0),  # Macquarie Island
    ]
    return pts


def fmt(*values):
    return ",".join(repr(float(v)) if not isinstance(v, (int, str)) else str(v) for v in values)


def write(name, header, rows):
    path = OUT / name
    with path.open("w") as f:
        f.write(versions())
        f.write(header + "\n")
        for r in rows:
            f.write(r + "\n")
    print(f"{path.name}: {len(rows)} rows")


def transformer(src, dst, expect):
    t = pyproj.Transformer.from_crs(src, dst, always_xy=True)
    assert expect in t.description, f"{src} -> {dst}: PROJ chose {t.description!r}"
    return t


def main():
    pts = points()
    to_ecef = pyproj.Transformer.from_crs("EPSG:7843", "EPSG:7842", always_xy=True)
    ecef = [to_ecef.transform(lon, lat, h) for lat, lon, h in pts]

    # Geodetic <-> ECEF on GRS80.
    write(
        "geodetic_ecef.csv",
        "lat_deg,lon_deg,h_m,x_m,y_m,z_m",
        [fmt(lat, lon, h, *xyz) for (lat, lon, h), xyz in zip(pts, ecef)],
    )

    # MGA2020 in each point's own zone and the next zone west (out-of-zone use).
    rows, rows_geodepy = [], []
    for lat, lon, _ in pts:
        own = int((lon + 180) // 6) + 1
        for zone in (own, own - 1):
            cm = zone * 6 - 183
            proj = pyproj.Proj(f"+proj=tmerc +lon_0={cm} +k=0.9996 +x_0=500000 +y_0=10000000 +ellps=GRS80 +algo=poder_engsager")
            e, n = proj(lon, lat)
            f = proj.get_factors(lon, lat)
            # PROJ's convergence is the bearing of grid north from true north;
            # MGA's is the opposite sign (grid bearing = azimuth + convergence).
            rows.append(fmt(lat, lon, zone, e, n, f.meridional_scale, -f.meridian_convergence))
            _, gzone, ge, gn, gk, ggc = geo2grid(lat, lon, zone=zone)
            assert gzone == zone
            rows_geodepy.append(fmt(lat, lon, zone, ge, gn, gk, ggc))
    write("mga_proj.csv", "lat_deg,lon_deg,zone,easting_m,northing_m,point_scale,convergence_deg", rows)
    write("mga_geodepy.csv", "lat_deg,lon_deg,zone,easting_m,northing_m,point_scale,convergence_deg", rows_geodepy)

    # Helmert transformations through PROJ's EPSG pipelines.
    gda94 = transformer("EPSG:4938", "EPSG:7842", "GDA94 to GDA2020 (1)")
    itrf14_gda20 = transformer("EPSG:7789", "EPSG:7842", "ITRF2014 to GDA2020 (1)")
    gda20_atrf14 = transformer("EPSG:7842", "EPSG:9307", "ATRF2014 to GDA2020 (1)")
    itrf20_itrf14 = transformer("EPSG:9988", "EPSG:7789", "ITRF2014 to ITRF2020 (1)")
    rows = []
    for x, y, z in ecef[::3]:
        rows.append(fmt("gda94_gda2020", 0.0, x, y, z, *gda94.transform(x, y, z)))
        for t in EPOCHS:
            rows.append(fmt("itrf2014_gda2020", t, x, y, z, *itrf14_gda20.transform(x, y, z, t)[:3]))
            rows.append(fmt("gda2020_atrf2014", t, x, y, z, *gda20_atrf14.transform(x, y, z, t)[:3]))
            rows.append(fmt("itrf2020_itrf2014", t, x, y, z, *itrf20_itrf14.transform(x, y, z, t)[:3]))
    write("helmert_proj.csv", "case,epoch,x_m,y_m,z_m,x_out_m,y_out_m,z_out_m", rows)

    # GeodePy's 7- and 14-parameter transformations with covariance propagation.
    def at_epoch(tr, dt):
        """GeodePy's Transformation.__add__, for an exact time difference in years,
        without its rounding and without mutating the shared uncertainties."""
        sd = copy.deepcopy(tr.tf_sd)
        grow = lambda a, b: math.hypot(a or 0.0, (b or 0.0) * dt)
        new_sd = TransformationSD(
            sd_tx=grow(sd.sd_tx, sd.sd_d_tx), sd_ty=grow(sd.sd_ty, sd.sd_d_ty), sd_tz=grow(sd.sd_tz, sd.sd_d_tz),
            sd_sc=grow(sd.sd_sc, sd.sd_d_sc), sd_rx=grow(sd.sd_rx, sd.sd_d_rx), sd_ry=grow(sd.sd_ry, sd.sd_d_ry),
            sd_rz=grow(sd.sd_rz, sd.sd_d_rz),
        )
        return Transformation(
            tr.from_datum, tr.to_datum, tr.ref_epoch,
            tr.tx + tr.d_tx * dt, tr.ty + tr.d_ty * dt, tr.tz + tr.d_tz * dt, tr.sc + tr.d_sc * dt,
            tr.rx + tr.d_rx * dt, tr.ry + tr.d_ry * dt, tr.rz + tr.d_rz * dt, tf_sd=new_sd,
        )

    def test_vcv(lat, lon):
        """A realistic covariance: 3, 4 and 9 mm east, north and up, with some correlation."""
        enu = np.array([[9e-6, 2e-6, 1e-6], [2e-6, 16e-6, -3e-6], [1e-6, -3e-6, 81e-6]])
        la, lo = math.radians(lat), math.radians(lon)
        r = np.array([
            [-math.sin(lo), math.cos(lo), 0.0],
            [-math.sin(la) * math.cos(lo), -math.sin(la) * math.sin(lo), math.cos(la)],
            [math.cos(la) * math.cos(lo), math.cos(la) * math.sin(lo), math.sin(la)],
        ])
        return r.T @ enu @ r

    def upper(m):
        return [m[0, 0], m[0, 1], m[0, 2], m[1, 1], m[1, 2], m[2, 2]]

    rows = []
    for (lat, lon, _), (x, y, z) in list(zip(pts, ecef))[::7]:
        vcv = test_vcv(lat, lon)
        cases = [("gda94_gda2020", 0.0, gda94_to_gda2020)]
        for t in (EPOCHS[0], EPOCHS[3], EPOCHS[-1]):
            dt = t - 2020.0
            cases.append(("itrf2014_gda2020", t, at_epoch(itrf2014_to_gda2020, dt)))
            cases.append(("gda2020_itrf2014", t, at_epoch(-itrf2014_to_gda2020, dt)))
            cases.append(("itrf2020_itrf2014", t, at_epoch(itrf2020_to_itrf2014, t - 2015.0)))
        for name, t, tr in cases:
            xo, yo, zo, vo = conform7(x, y, z, tr, vcv=vcv)
            rows.append(fmt(name, t, x, y, z, *upper(vcv), xo, yo, zo, *upper(vo)))
    write(
        "helmert_geodepy.csv",
        "case,epoch,x_m,y_m,z_m,cxx,cxy,cxz,cyy,cyz,czz,x_out_m,y_out_m,z_out_m,oxx,oxy,oxz,oyy,oyz,ozz",
        rows,
    )


if __name__ == "__main__":
    main()
