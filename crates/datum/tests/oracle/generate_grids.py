"""Generate the reference data for the datum crate's grid tests.

The published grids are too big to commit (AUSGeoid2020 is 247 MB), so this
crops small windows around test points into test grids, and computes reference
values from the full published grids:

- NTv2 test grids are written here, node records copied unchanged.
- GeoTIFF test grids are written by GDAL (through rasterio) in PROJ's
  conventions, so the reader is tested against an independent writer.
- PROJ checks each test grid gives exactly what the full grid gives at the
  test points, and supplies the reference values: GDA94 to GDA2020 by
  `hgridshift` (both directions) and the conformal transformation (EPSG:8048)
  for heights, and AUSGeoid2020's N by `vgridshift`.
- GeodePy supplies the GDA94 to GDA2020 shifts and accuracies from the NTv2
  test grid, by its own NTv2 reader.
- AUSGeoid2020's uncertainty has no other implementation to compare with, so
  it's interpolated here with NumPy from the full uncertainty grid.

It also writes reference values at random points over the full grids, for
`tests/grids.rs`'s test of the published files themselves (run when
`GNSS_GRID_DIR` points to them).

Its inputs are the four grid files packs/au/pack.toml lists, checked against
the SHA-256 there: Geoscience Australia's AUSGeoid2020_20180201.gsb and
AUSGeoid2020_20180201_error.gsb, and PROJ-data's au_ga_AUSGeoid2020_20180201.tif
and au_icsm_GDA94_GDA2020_conformal_and_distortion.tif. Run from the
repository root:

    python3 crates/datum/tests/oracle/fetch_grids.py <directory>
    python3 -m venv .venv
    .venv/bin/pip install geodepy==0.7.0 pyproj==3.8.0 numpy==2.2.6 rasterio==1.5.2
    .venv/bin/python -I crates/datum/tests/oracle/generate_grids.py --grids <directory>
"""

import argparse
import hashlib
import importlib.metadata
import struct
import sys
import tomllib
from pathlib import Path

import numpy as np
import pyproj
import rasterio
from geodepy.ntv2reader import interpolate_ntv2, read_ntv2_file
from rasterio.windows import Window

PACK = Path(__file__).resolve().parents[4] / "packs" / "au" / "pack.toml"
GRIDS = {
    f["file"]: f["sha256"]
    for grid in tomllib.loads(PACK.read_text())["grids"]
    for f in grid["files"]
}

OUT = Path(__file__).resolve().parent.parent / "data" / "grids"
SEED = 2026
# Test points per ICSM subgrid, and over AUSGeoid2020.
POINTS_PER_SUBGRID = 8
GEOID_POINTS = 32
# Random points over the full grids, for the published-file test.
FULL_POINTS = 400


# Crops recompute their limits in floating point, so a crop and the full grid
# can place nodes a few units in the last place apart.
SAME_DEG = 1e-12
SAME_M = 1e-9


def header_line():
    return (
        f"# Generated by tests/oracle/generate_grids.py with GeodePy "
        f"{importlib.metadata.version('geodepy')}, NumPy {np.__version__}, pyproj "
        f"{pyproj.__version__}, PROJ {pyproj.proj_version_str}, rasterio {rasterio.__version__}, "
        f"GDAL {rasterio.__gdal_version__}\n"
    )


def same(a, b, tolerance):
    return all(abs(x - y) <= tolerance for x, y in zip(a, b))


def check_inputs(directory):
    for name, expected in GRIDS.items():
        path = directory / name
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest != expected:
            sys.exit(f"{path}: SHA-256 {digest}, expected {expected}")


# --- NTv2 ------------------------------------------------------------------

def record(key, value):
    return key.encode().ljust(8) + value


def text(value):
    return value.encode().ljust(8)[:8]


def write_ntv2(path, system_f, system_t, version, subgrids):
    """subgrids: (name, s_lat, n_lat, e_long, w_long, lat_inc, long_inc, nodes),
    limits in arc-seconds (longitude positive west), nodes as bytes in file order."""
    out = bytearray()
    i32 = lambda v: struct.pack("<i", v) + b"\0" * 4
    f64 = lambda v: struct.pack("<d", v)
    out += record("NUM_OREC", i32(11)) + record("NUM_SREC", i32(11))
    out += record("NUM_FILE", i32(len(subgrids))) + record("GS_TYPE", text("SECONDS"))
    out += record("VERSION", text(version)) + record("SYSTEM_F", text(system_f))
    out += record("SYSTEM_T", text(system_t))
    for key in ("MAJOR_F", "MINOR_F", "MAJOR_T", "MINOR_T"):
        out += record(key, f64(6378137.0 if key.startswith("MAJOR") else 6356752.314))
    for name, s_lat, n_lat, e_long, w_long, lat_inc, long_inc, nodes in subgrids:
        out += record("SUB_NAME", text(name)) + record("PARENT", text("NONE"))
        out += record("CREATED", text("19102026")) + record("UPDATED", text("19102026"))
        for key, v in (("S_LAT", s_lat), ("N_LAT", n_lat), ("E_LONG", e_long),
                       ("W_LONG", w_long), ("LAT_INC", lat_inc), ("LONG_INC", long_inc)):
            out += record(key, f64(v))
        out += record("GS_COUNT", i32(len(nodes) // 16))
        out += nodes
    out += record("END", b"\0" * 8)
    path.write_bytes(bytes(out))


class Ntv2:
    """The one-subgrid AUSGeoid2020 NTv2 files, read directly."""

    def __init__(self, path):
        self.data = path.read_bytes()
        h = self.data[176:352]
        val = lambda i: struct.unpack("<d", h[i * 16 + 8:i * 16 + 16])[0]
        self.s_lat, self.n_lat, self.e_long, self.w_long, self.lat_inc, self.long_inc = (
            val(4), val(5), val(6), val(7), val(8), val(9))
        self.rows = round((self.n_lat - self.s_lat) / self.lat_inc) + 1
        self.cols = round((self.w_long - self.e_long) / self.long_inc) + 1
        self.nodes = np.frombuffer(self.data, dtype="<f4", offset=352, count=self.rows * self.cols * 4)
        self.nodes = self.nodes.reshape(self.rows, self.cols, 4)

    def cell(self, lat, lon):
        """Row and NTv2 column (from the east) of the node south-east of a point,
        and the point's fractions north and west across the cell."""
        y = (lat * 3600 - self.s_lat) / self.lat_inc
        x = (-lon * 3600 - self.e_long) / self.long_inc
        r, c = int(np.floor(y)), int(np.floor(x))
        return r, c, y - r, x - c

    def bilinear(self, lat, lon, field, has_value):
        """Bilinear interpolation over the nodes that have a value, with the
        weights rescaled, as PROJ interpolates vertical grids."""
        r, c, fy, fx = self.cell(lat, lon)
        v = self.nodes[r:r + 2, c:c + 2, field].astype(np.float64)
        w = np.array([[(1 - fx) * (1 - fy), fx * (1 - fy)], [(1 - fx) * fy, fx * fy]])
        ok = has_value(v)
        return float((v[ok] * w[ok]).sum() / w[ok].sum()) if w[ok].sum() > 0 else float("nan")

    def window(self, name, r0, c0, rows, cols):
        nodes = self.nodes[r0:r0 + rows, c0:c0 + cols, :].astype("<f4").tobytes()
        return (name, self.s_lat + r0 * self.lat_inc, self.s_lat + (r0 + rows - 1) * self.lat_inc,
                self.e_long + c0 * self.long_inc, self.e_long + (c0 + cols - 1) * self.long_inc,
                self.lat_inc, self.long_inc, nodes)


# --- PROJ ------------------------------------------------------------------

def hgridshift(path):
    return pyproj.Transformer.from_pipeline(
        f"+proj=pipeline +step +proj=unitconvert +xy_in=deg +xy_out=rad "
        f"+step +proj=hgridshift +grids={path} +step +proj=unitconvert +xy_in=rad +xy_out=deg")


def vgridshift(path):
    return pyproj.Transformer.from_pipeline(
        f"+proj=pipeline +step +proj=unitconvert +xy_in=deg +xy_out=rad "
        f"+step +proj=vgridshift +grids={path} +multiplier=1 "
        f"+step +proj=unitconvert +xy_in=rad +xy_out=deg")


# EPSG:8048 on geographic coordinates, for ellipsoidal heights.
CONFORMAL = pyproj.Transformer.from_pipeline(
    "+proj=pipeline +step +proj=unitconvert +xy_in=deg +xy_out=rad +step +proj=cart +ellps=GRS80 "
    "+step +proj=helmert +x=0.06155 +y=-0.01087 +z=-0.04019 +rx=-0.0394924 +ry=-0.0327221 "
    "+rz=-0.0328979 +s=-0.009994 +convention=coordinate_frame "
    "+step +inv +proj=cart +ellps=GRS80 +step +proj=unitconvert +xy_in=rad +xy_out=deg")
CART = pyproj.Transformer.from_pipeline("+proj=pipeline +step +proj=unitconvert +xy_in=deg +xy_out=rad "
                                        "+step +proj=cart +ellps=GRS80")


# --- GDA94 to GDA2020 --------------------------------------------------------

def icsm_points(icsm, rng):
    """Test points inside each ICSM subgrid, at least three nodes from its
    edges, half of them where the grid gives accuracies; plus two on nodes and
    one on a row of nodes. Returns (subgrid index, lat, lon) with each
    subgrid's dataset path."""
    with rasterio.open(icsm) as ds:
        paths = [icsm] + list(ds.subdatasets)[1:]
    points = []
    for k, p in enumerate(paths):
        with rasterio.open(p) as ds:
            acc = ds.read(3)
            t = ds.transform
            res = t.a
            west, north = t.c + res / 2, t.f - res / 2
            # Cells whose four nodes all give accuracies, three nodes from the edges.
            known = (acc[:-1, :-1] >= 0) & (acc[1:, :-1] >= 0) & (acc[:-1, 1:] >= 0) & (acc[1:, 1:] >= 0)
            cells = np.argwhere(known[3:-4, 3:-4]) + 3
            # QLD_C_5 gives accuracies at almost no nodes.
            want_known = min(POINTS_PER_SUBGRID // 2, len(cells))
            for i in range(POINTS_PER_SUBGRID):
                if i < want_known:
                    ri, ci = cells[rng.integers(len(cells))]
                    r, c = ri + rng.uniform(0.05, 0.95), ci + rng.uniform(0.05, 0.95)
                else:
                    r, c = rng.uniform(3, ds.height - 4), rng.uniform(3, ds.width - 4)
                points.append((k, north - r * res, west + c * res))
            if k == 0:
                points.append((k, north - 100 * res, west + 200 * res))  # on a node
                points.append((k, north - 300.5 * res, west + 400 * res))  # on a column of nodes
                points.append((k, north - 500 * res, west + 600.25 * res))  # on a row of nodes
    return paths, points


def icsm_windows(paths, points, rng):
    """4 × 4 node windows around each point, as (subgrid path, name, row0, col0, rows, cols)
    in image rows from the north. Then one large window in CENT_DC5, which
    spans several of the test GeoTIFF's tiles, and points inside it that have
    no window of their own."""
    windows = []
    for i, (k, lat, lon) in enumerate(points):
        with rasterio.open(paths[k]) as ds:
            res = ds.transform.a
            west, north = ds.transform.c + res / 2, ds.transform.f - res / 2
            r = int(np.floor((north - lat) / res + 1e-9))
            c = int(np.floor((lon - west) / res + 1e-9))
            windows.append((paths[k], f"W{i:03d}", r - 1, c - 1, 4, 4))
    r0, c0, rows, cols = 900, 100, 40, 36
    windows.append((paths[1], "BIG", r0, c0, rows, cols))
    with rasterio.open(paths[1]) as ds:
        res = ds.transform.a
        west, north = ds.transform.c + res / 2, ds.transform.f - res / 2
    for _ in range(6):
        r = rng.uniform(r0 + 1, r0 + rows - 2)
        c = rng.uniform(c0 + 1, c0 + cols - 2)
        points.append((1, north - r * res, west + c * res))
    return windows


def write_icsm_ntv2(windows, path):
    subgrids = []
    for src, name, r0, c0, rows, cols in windows:
        with rasterio.open(src) as ds:
            a = ds.read(window=Window(c0, r0, cols, rows)).astype(np.float64)
            res_s = round(ds.transform.a * 3600)
            west_s = round((ds.transform.c + ds.transform.a / 2) * 3600) + c0 * res_s
            north_s = round((ds.transform.f - ds.transform.a / 2) * 3600) - r0 * res_s
        # NTv2: rows from the south, columns from the east, longitude positive west.
        nodes = np.empty((rows, cols, 4), dtype="<f4")
        for rr in range(rows):
            for cc in range(cols):
                src_r, src_c = rows - 1 - rr, cols - 1 - cc
                nodes[rr, cc] = (a[0, src_r, src_c], -a[1, src_r, src_c], a[2, src_r, src_c], a[3, src_r, src_c])
        south_s = north_s - (rows - 1) * res_s
        east_s = west_s + (cols - 1) * res_s
        subgrids.append((name, float(south_s), float(north_s), float(-east_s), float(-west_s),
                         float(res_s), float(res_s), nodes.tobytes()))
    write_ntv2(path, "GDA94", "GDA2020", "NAT_DC6", subgrids)


def write_geotiff(path, windows, read, tags, band_info, nodata=None, area=False, **options):
    """Writes windows as GDAL images, one per subgrid, appending after the first."""
    for i, (src, name, r0, c0, rows, cols) in enumerate(windows):
        with rasterio.open(src) as ds:
            data = read(ds, Window(c0, r0, cols, rows))
            transform = ds.window_transform(Window(c0, r0, cols, rows))
            crs = ds.crs
        profile = dict(driver="GTiff", width=cols, height=rows, count=data.shape[0],
                       dtype="float32", crs=crs, transform=transform, nodata=nodata, **options)
        if i > 0:
            profile["APPEND_SUBDATASET"] = "YES"
        with rasterio.open(path, "w", **profile) as dst:
            dst.write(data.astype(np.float32))
            dst.update_tags(AREA_OR_POINT="Area" if area else "Point", grid_name=name, **tags)
            for b, (description, unit, extra) in enumerate(band_info, start=1):
                dst.set_band_description(b, description)
                dst.set_band_unit(b, unit)
                if extra:
                    dst.update_tags(b, **extra)


def gda94_gda2020(grids, rng):
    icsm = grids / "au_icsm_GDA94_GDA2020_conformal_and_distortion.tif"
    paths, points = icsm_points(str(icsm), rng)
    windows = icsm_windows(paths, points, rng)
    gsb = OUT / "gda94_gda2020_crop.gsb"
    tif = OUT / "gda94_gda2020_crop.tif"
    write_icsm_ntv2(windows, gsb)
    write_geotiff(
        tif, windows, lambda ds, w: ds.read(window=w),
        dict(TYPE="HORIZONTAL_OFFSET", target_crs_epsg_code="7844",
             TIFFTAG_IMAGEDESCRIPTION="Test windows of GDA94 (EPSG:4283) to GDA2020 (EPSG:7844), "
                                      "from au_icsm_GDA94_GDA2020_conformal_and_distortion.tif"),
        [("latitude_offset", "arc-second", None), ("longitude_offset", "arc-second", {"positive_value": "east"}),
         ("latitude_offset_accuracy", "arc-second", None), ("longitude_offset_accuracy", "arc-second", None)],
        area=True, tiled=True, blockxsize=16, blockysize=16, compress="deflate", predictor=3,
        interleave="band")

    full, crop_gsb, crop_tif = hgridshift(icsm), hgridshift(gsb), hgridshift(tif)
    ntv2 = read_ntv2_file(str(gsb))
    heights = [-35.0, 120.5, 650.0, 2228.0]
    rows = []
    for i, (_, lat, lon) in enumerate(points):
        h = heights[i % 4]
        lon2, lat2 = full.transform(lon, lat)
        for t in (crop_gsb, crop_tif):
            assert same(t.transform(lon, lat), (lon2, lat2), SAME_DEG), (t, lat, lon)
        # GDA2020 to GDA94, from the untransformed point read as GDA2020.
        lon3, lat3 = full.transform(lon, lat, direction="INVERSE")
        for t in (crop_gsb, crop_tif):
            assert same(t.transform(lon, lat, direction="INVERSE"), (lon3, lat3), SAME_DEG)
        _, _, h2 = CONFORMAL.transform(lon, lat, h)
        x, y, z = CART.transform(lon2, lat2, h2)
        lat_s, lon_w, lat_acc, lon_acc = interpolate_ntv2(ntv2, lat, lon, method="bilinear")
        rows.append([lat, lon, h, lat2, lon2, h2, x, y, z, lat3, lon3, lat_s, -lon_w, lat_acc, lon_acc])
    path = OUT / "gda94_gda2020.csv"
    with path.open("w") as f:
        f.write(header_line())
        f.write("lat,lon,h,lat_2020,lon_2020,h_2020,x_2020,y_2020,z_2020,lat_94_from_2020,"
                "lon_94_from_2020,geodepy_lat_shift_s,geodepy_lon_shift_east_s,geodepy_lat_acc_s,"
                "geodepy_lon_acc_s\n")
        for r in rows:
            f.write(",".join(repr(float(v)) for v in r) + "\n")

    # Random points over the full grid, for the published-file test.
    full_rows = []
    with rasterio.open(str(icsm)) as ds:
        subs = [str(icsm)] + list(ds.subdatasets)[1:]
    for p in subs:
        with rasterio.open(p) as ds:
            b = ds.bounds
            for _ in range(FULL_POINTS // len(subs)):
                lat = rng.uniform(b.bottom + 0.05, b.top - 0.05)
                lon = rng.uniform(b.left + 0.05, b.right - 0.05)
                lon2, lat2 = full.transform(lon, lat)
                lon3, lat3 = full.transform(lon, lat, direction="INVERSE")
                full_rows.append([lat, lon, lat2, lon2, lat3, lon3])
    with (OUT / "gda94_gda2020_full.csv").open("w") as f:
        f.write(header_line())
        f.write("lat,lon,lat_2020,lon_2020,lat_94_from_2020,lon_94_from_2020\n")
        for r in full_rows:
            f.write(",".join(repr(float(v)) for v in r) + "\n")
    return len(rows), len(full_rows)


# --- AUSGeoid2020 ------------------------------------------------------------

def geoid_points(geoid, rng):
    """Land points: every node of the 4 × 4 window around each has a value."""
    points = []
    while len(points) < GEOID_POINTS:
        lat, lon = rng.uniform(-43.5, -10.5), rng.uniform(113.5, 153.5)
        r, c, _, _ = geoid.cell(lat, lon)
        if (geoid.nodes[r - 1:r + 3, c - 1:c + 3, 0] != -999).all():
            points.append((lat, lon))
    # A point at the edge of the model's coverage, offshore, where some but
    # not all of the cell's nodes have no value.
    for _ in range(1_000_000):
        lat, lon = rng.uniform(-60.0, -9.0), rng.uniform(94.0, 173.0)
        r, c, _, _ = geoid.cell(lat, lon)
        v = geoid.nodes[r:r + 2, c:c + 2, 0]
        if (v == -999).any() and (v != -999).any():
            points.append((lat, lon))
            return points
    sys.exit("no coastal point found")


def ausgeoid2020(grids, rng):
    geoid = Ntv2(grids / "AUSGeoid2020_20180201.gsb")
    error = Ntv2(grids / "AUSGeoid2020_20180201_error.gsb")
    tif = grids / "au_ga_AUSGeoid2020_20180201.tif"
    points = geoid_points(geoid, rng)

    gsb_windows, err_windows, tif_windows = [], [], []
    with rasterio.open(str(tif)) as ds:
        res = ds.transform.a
        west, north = ds.transform.c + res / 2, ds.transform.f - res / 2
    for i, (lat, lon) in enumerate(points):
        r, c, _, _ = geoid.cell(lat, lon)
        # NTv2 columns count from the east; the window's south-east node is (r - 1, c - 1).
        gsb_windows.append(geoid.window(f"W{i:03d}", r - 1, c - 1, 4, 4))
        err_windows.append(error.window(f"W{i:03d}", r - 1, c - 1, 4, 4))
        # The same nodes in PROJ's GeoTIFF, whose rows run from the north.
        tr = int(np.floor((north - lat) / res))
        tc = int(np.floor((lon - west) / res))
        tif_windows.append((str(tif), f"W{i:03d}", tr - 1, tc - 1, 4, 4))
    gsb = OUT / "ausgeoid2020_crop.gsb"
    err = OUT / "ausgeoid2020_error_crop.gsb"
    crop_tif = OUT / "ausgeoid2020_crop.tif"
    write_ntv2(gsb, "GDA2020", "AHD71", "1.0.0.1", gsb_windows)
    write_ntv2(err, "GDA94", "AHD_1971", "1.0.0.0", err_windows)
    write_geotiff(
        crop_tif, tif_windows, lambda ds, w: ds.read(window=w),
        dict(TYPE="VERTICAL_OFFSET_GEOGRAPHIC_TO_VERTICAL", target_crs_epsg_code="5711",
             TIFFTAG_IMAGEDESCRIPTION="Test windows of GDA2020 (EPSG:7843) to AHD height (EPSG:5711), "
                                      "from au_ga_AUSGeoid2020_20180201.tif"),
        [("geoid_undulation", "metre", None)], nodata=-32768.0,
        tiled=False, blockysize=3, compress="deflate", predictor=3)

    full, cropped = vgridshift(tif), vgridshift(crop_tif)
    rows = []
    for lat, lon in points:
        _, _, n = full.transform(lon, lat, 0.0)
        if np.isfinite(n):
            assert abs(cropped.transform(lon, lat, 0.0)[2] - n) <= SAME_M, (lat, lon)
        sigma = error.bilinear(lat, lon, 0, lambda v: v > 0)
        rows.append([lat, lon, n if np.isfinite(n) else float("nan"), sigma])
    with (OUT / "ausgeoid2020.csv").open("w") as f:
        f.write(header_line())
        f.write("lat,lon,n,sigma_n\n")
        for r in rows:
            f.write(",".join(repr(float(v)) for v in r) + "\n")

    full_rows = []
    while len(full_rows) < FULL_POINTS:
        lat, lon = rng.uniform(-44.0, -10.0), rng.uniform(113.0, 154.0)
        r, c, _, _ = geoid.cell(lat, lon)
        if (geoid.nodes[r:r + 2, c:c + 2, 0] == -999).any():
            continue
        _, _, n = full.transform(lon, lat, 0.0)
        full_rows.append([lat, lon, n, error.bilinear(lat, lon, 0, lambda v: v > 0)])
    with (OUT / "ausgeoid2020_full.csv").open("w") as f:
        f.write(header_line())
        f.write("lat,lon,n,sigma_n\n")
        for r in full_rows:
            f.write(",".join(repr(float(v)) for v in r) + "\n")
    return len(rows), len(full_rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--grids", type=Path, required=True,
                        help="directory holding the published grid files")
    args = parser.parse_args()
    pyproj.network.set_network_enabled(False)
    check_inputs(args.grids)
    OUT.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(SEED)
    print("GDA94 to GDA2020 points (test, full):", gda94_gda2020(args.grids, rng))
    print("AUSGeoid2020 points (test, full):", ausgeoid2020(args.grids, rng))
    for p in sorted(OUT.iterdir()):
        print(f"  {p.name}: {p.stat().st_size} bytes")


if __name__ == "__main__":
    main()
