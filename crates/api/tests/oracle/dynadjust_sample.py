#!/usr/bin/env python3
"""Adjust DynAdjust's sample GNSS network with DynAdjust and store the results.

The network is DynAdjust's own sample (crates/formats/tests/data/dynaml): real
baselines in ITRF2008 and ITRF2014 at their observation epochs, and a cluster
of positions in GDA2020. DynAdjust imports it, transforms the measurements to
GDA2020 with dnareftran, and adjusts it. The results go to
`tests/data/dynadjust/gnss-network.csv`, which `tests/dynaml.rs` compares
against our import and adjustment of the same files.

Build DynAdjust as `crates/adjust/tests/oracle/dynadjust.py` describes, then:

    python3 -I crates/api/tests/oracle/dynadjust_sample.py DynAdjust/bin

Free stations get a 1 km a priori constraint rather than DynAdjust's 10 m, so
it changes nothing at the precision compared.
"""

import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent.parent
SAMPLE = CRATE.parent / "formats" / "tests" / "data" / "dynaml"
OUT = CRATE / "tests" / "data" / "dynadjust" / "gnss-network.csv"
FILES = ["gnss-networkstn.xml", "gnss-networkmsr.xml"]
ADJUST_OPTIONS = [
    "--simultaneous-adjustment",
    "--output-adj-msr",
    "--output-pos-uncertainty",
    "--output-json",
    "--free-stn-sd",
    "1000",
    "--max-iterations",
    "20",
]


def records(path):
    with open(path) as f:
        for line in f:
            yield json.loads(line)


def as_list(value):
    return value if isinstance(value, list) else [value]


def describe(binaries):
    try:
        return subprocess.run(
            ["git", "-C", str(binaries.parent), "describe", "--tags", "--always"],
            capture_output=True, text=True, check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main():
    binaries = Path(sys.argv[1]).resolve()
    run = lambda *args: subprocess.run(  # noqa: E731
        [str(binaries / args[0]), *args[1:]], cwd=work, check=True, stdout=subprocess.DEVNULL
    )
    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)
        for name in FILES:
            shutil.copy(SAMPLE / name, work / name)
        run("dnaimport", "-n", "gnss", *FILES)
        run("dnareftran", "gnss", "-r", "GDA2020")
        run("dnaadjust", "gnss", *ADJUST_OPTIONS)
        software, statistics, measurements = None, None, []
        for record in records(work / "gnss.simult.adj.jsonl"):
            if "DnaAdjustmentReport" in record:
                software = record["DnaAdjustmentReport"]["software"]
            elif "DnaStatistics" in record:
                statistics = record["DnaStatistics"]
            elif "DnaMeasurement" in record:
                measurements.append(record["DnaMeasurement"])
        stations = [
            r["DnaStation"] for r in records(work / "gnss.simult.xyz.jsonl") if "DnaStation" in r
        ]

    lines = [
        f"# Generated by tests/oracle/dynadjust_sample.py with {software} ({describe(binaries)}): "
        f"dnaimport, dnareftran -r GDA2020, dnaadjust {' '.join(ADJUST_OPTIONS)}",
        f"statistics,{statistics['chisq']!r},{statistics['dof']},{statistics['sigma_zero']!r}",
    ]
    for s in stations:
        adjusted = s["Adjusted"]
        u = s.get("Uncertainty", {})
        lines.append(
            f"station,{s['Name']},{adjusted['X']!r},{adjusted['Y']!r},{adjusted['Z']!r},"
            f"{u.get('HzPosU', 0.0)!r},{u.get('VtPosU', 0.0)!r}"
        )
    # Measured values are after dnareftran, and sigmas after variance scaling.
    for index, m in enumerate(measurements):
        parts = as_list(m.get("GPSBaseline") or m.get("Clusterpoint"))
        for element, (part, nstat) in enumerate(zip(parts, as_list(m["NStat"]))):
            sigmas = [part[k] for k in ["SigmaXX", "SigmaXY", "SigmaXZ", "SigmaYY", "SigmaYZ", "SigmaZZ"]]
            values = [part["X"], part["Y"], part["Z"]] + sigmas + [nstat["X"], nstat["Y"], nstat["Z"]]
            lines.append(
                f"element,{m['Type']},{index},{element},{part['First']},{part.get('Second', '')},"
                + ",".join(repr(float(v)) for v in values)
            )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(stations)} stations, {len(measurements)} measurements, "
          f"sigma zero {statistics['sigma_zero']:.4f}")


if __name__ == "__main__":
    main()
