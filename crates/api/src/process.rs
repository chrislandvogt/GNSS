//! Processing baselines with RTKLIB-EX (M8, ARCHITECTURE.md section 9.3):
//! `gnss process`.
//!
//! For each baseline, the inputs are prepared here and the engine runs them
//! through [`Engine`], which the CLI provides with wasmtime and the web app
//! will with its workers:
//!
//! - **Baselines.** Every pair of occupations that overlap
//!   ([`gnss_model::candidates`]), and every occupation against every CORS
//!   station whose observations `gnss fetch` got for it. Choosing the
//!   independent ones comes later; for now all are processed.
//! - **Observations.** A field occupation's RINEX with its overlays applied,
//!   and a CORS station's files joined; both trimmed to the overlap
//!   ([`gnss_rinex_io::trim_obs`]).
//! - **Navigation data** from `data.toml`, which must cover every
//!   constellation processed over the overlap, or the baseline isn't run.
//! - **ANTEX**, the pinned file `gnss fetch` got, uncompressed.
//! - **The configuration**, from `[processing]` ([`gnss_engine_rtklib`]).
//!
//! Each solution is kept as `results/baselines/<base>_<rover>.pos`. Fixed
//! ones are recorded in `project.toml` as RTKLIB imports, so `gnss adjust`
//! uses them; floats and failures are reported, not used.

use std::io::Read;

use gnss_engine_rtklib::{Base, Direction, Orbits, Run};
use gnss_fetch::Cache;
use gnss_fetch::plan::ANTEX;
use gnss_model::{DataFiles, Occupation, Timestamp, candidates};
use gnss_rinex_io::{GnssTime, HeaderPatch, NavFile, Trim, read_nav, read_obs, trim_obs};
use gnss_store::{ProjectPath, Store, StoreError};
use hifitime::TimeScale;
use serde::Serialize;

use crate::folder::{LoadError, load};
use crate::project::{Format, Import, Project, ProjectError};

/// By default, occupations must overlap by this long, in seconds, to be
/// processed.
pub const MIN_OVERLAP: f64 = 600.0;

/// Where solutions are kept.
pub const RESULTS: &str = "results/baselines";

/// Whether a project file is a solution this writes: regenerated by
/// processing, so not a raw file kept in `raw.lock`.
pub fn is_result(file: &str) -> bool {
    file.starts_with(&format!("{RESULTS}/"))
}

/// Runs the engine: `rnx2rtkp` with arguments, in a folder holding the
/// inputs, giving back the file it was told to write.
pub trait Engine {
    /// One run. An error is the run not happening (a trap or time-out);
    /// a run that happens and fails is a non-zero status.
    fn run(
        &mut self,
        inputs: &[(String, Vec<u8>)],
        args: &[String],
        output: &str,
    ) -> Result<EngineRun, String>;
}

/// What a run gave back.
#[derive(Debug, Clone, PartialEq)]
pub struct EngineRun {
    /// Its exit status: 0 for success.
    pub status: i32,
    /// What it wrote to standard error.
    pub stderr: String,
    /// The output file, if it wrote one.
    pub output: Option<Vec<u8>>,
}

/// One baseline's outcome.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct Processed {
    /// The base: an occupation's mark, or a CORS station.
    pub base: String,
    /// The rover's mark.
    pub rover: String,
    /// The overlap processed, UTC.
    pub start: String,
    /// See `start`.
    pub end: String,
    /// The solution file, if there was a solution.
    pub file: Option<String>,
    /// `fixed`, `float` or another of RTKLIB's solution kinds.
    pub quality: Option<String>,
    /// Satellites in the solution.
    pub satellites: Option<u32>,
    /// The ambiguity ratio test's value.
    pub ratio: Option<f64>,
    /// The baseline's length, metres.
    pub length: Option<f64>,
    /// Whether it's recorded for the adjustment (fixed solutions only).
    pub used: bool,
    /// Why it wasn't processed or isn't used.
    pub problem: Option<String>,
}

/// What processing did.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct Report {
    /// The baselines, in order.
    pub baselines: Vec<Processed>,
    /// Anything to know about the whole run.
    pub notes: Vec<String>,
}

/// Why processing couldn't start.
#[derive(Debug, thiserror::Error)]
pub enum ProcessError {
    /// The project doesn't load.
    #[error(transparent)]
    Load(#[from] LoadError),
    /// `project.toml` couldn't be written.
    #[error(transparent)]
    Project(#[from] ProjectError),
    /// The project folder or the download cache failed.
    #[error(transparent)]
    Store(#[from] StoreError),
    /// Something the run needs is missing.
    #[error("{0}")]
    Missing(String),
}

/// One end of a baseline.
struct End {
    /// The mark or station.
    mark: String,
    /// For file names: the occupation's id, or the station.
    label: String,
    start: Timestamp,
    end: Timestamp,
    /// The observations, before trimming, each with its overlays.
    files: Vec<(Vec<u8>, HeaderPatch)>,
}

/// Processes every baseline the project has data for whose ends overlap by
/// at least `min_overlap` seconds ([`MIN_OVERLAP`]), keeps the solutions and
/// records the fixed ones for the adjustment.
pub fn process<S: Store + ?Sized, C: Store, E: Engine>(
    store: &mut S,
    cache: &Cache<C>,
    engine: &mut E,
    min_overlap: f64,
) -> Result<Report, ProcessError> {
    let loaded = load(store)?;
    let settings = loaded.project.processing.clone();
    let data = match store.read(&ProjectPath::new("data.toml")?)? {
        Some(bytes) => DataFiles::from_toml(&String::from_utf8_lossy(&bytes))
            .map_err(|e| ProcessError::Missing(format!("data.toml: {e}")))?,
        None => {
            return Err(ProcessError::Missing(
                "there's no data.toml: run gnss fetch first, for navigation data and ANTEX".into(),
            ));
        }
    };
    let from_cache = |source: &str, name: &str| -> Result<Vec<u8>, ProcessError> {
        let entry = cache.get(source, name)?.ok_or_else(|| {
            ProcessError::Missing(format!(
                "{name} isn't in the download cache: run gnss fetch again"
            ))
        })?;
        cache.read(&entry)?.ok_or_else(|| {
            ProcessError::Missing(format!(
                "{name} is damaged in the download cache: run gnss fetch again"
            ))
        })
    };

    // Navigation data: every file, uncompressed, and their ephemerides
    // together for the coverage check.
    let mut nav_files = Vec::new();
    let mut ephemerides = NavFile {
        version: gnss_rinex_io::Version { major: 3, minor: 4 },
        ephemerides: Vec::new(),
    };
    for file in data
        .files
        .iter()
        .filter(|f| f.purpose.starts_with("navigation data"))
    {
        let plain = gunzip(&from_cache(&file.source, &file.name)?)
            .map_err(|e| ProcessError::Missing(format!("{}: {e}", file.name)))?;
        let nav = read_nav(&plain[..])
            .map_err(|e| ProcessError::Missing(format!("{}: {e}", file.name)))?;
        ephemerides.ephemerides.extend(nav.ephemerides);
        nav_files.push(plain);
    }
    if nav_files.is_empty() {
        return Err(ProcessError::Missing(
            "data.toml lists no navigation data: run gnss fetch".into(),
        ));
    }
    let antex = data.files.iter().find(|f| f.name == ANTEX).ok_or_else(|| {
        ProcessError::Missing(format!("data.toml has no {ANTEX}: run gnss fetch"))
    })?;
    let antex = gunzip(&from_cache(&antex.source, &antex.name)?)
        .map_err(|e| ProcessError::Missing(format!("{ANTEX}: {e}")))?;
    let antex_name = ANTEX.trim_end_matches(".gz").to_owned();

    // The ends: field occupations, and CORS stations.
    let mut notes = Vec::new();
    let field = |o: &Occupation| -> Result<End, ProcessError> {
        let mut files = Vec::new();
        for file in &o.rinex {
            let bytes = store.read_raw(&ProjectPath::new(file.as_str())?)?;
            files.push((bytes, crate::reconcile::patch_for(&loaded.overlays, file)));
        }
        Ok(End {
            mark: o.mark.to_string(),
            label: o.id.to_string(),
            start: o.start,
            end: o.end,
            files,
        })
    };
    let mut cors: Vec<End> = Vec::new();
    for file in &data.files {
        let Some((station, window)) = file.purpose.split_once(" observations, ") else {
            continue;
        };
        let Some((start, end)) = gps_window(window) else {
            notes.push(format!(
                "{}: its window doesn't read: {}",
                file.name, file.purpose
            ));
            continue;
        };
        let bytes = from_cache(&file.source, &file.name)?;
        match cors.iter_mut().find(|c| c.mark == station) {
            Some(c) => {
                c.start = earlier(c.start, start);
                c.end = later(c.end, end);
                c.files.push((bytes, HeaderPatch::default()));
            }
            None => cors.push(End {
                mark: station.to_owned(),
                label: station.to_owned(),
                start,
                end,
                files: vec![(bytes, HeaderPatch::default())],
            }),
        }
    }

    // The baselines.
    let mut pairs: Vec<(End, End)> = Vec::new();
    for c in candidates(&loaded.occupations, min_overlap) {
        let find = |id| loaded.occupations.iter().find(|o| o.id == id);
        if let (Some(a), Some(b)) = (find(c.from.clone()), find(c.to.clone())) {
            pairs.push((field(a)?, field(b)?));
        }
    }
    for o in &loaded.occupations {
        for c in &cors {
            let start = later(o.start, c.start);
            let end = earlier(o.end, c.end);
            if start.seconds_until(end) >= min_overlap {
                let base = End {
                    mark: c.mark.clone(),
                    label: c.label.clone(),
                    start: c.start,
                    end: c.end,
                    files: c.files.clone(),
                };
                pairs.push((base, field(o)?));
            }
        }
    }
    if pairs.is_empty() {
        notes.push(format!(
            "no baselines: no occupations overlap each other or the fetched CORS data by {} minutes",
            min_overlap / 60.0
        ));
    }

    let systems: Vec<char> = settings.constellations.iter().map(|c| c.letter()).collect();
    let mut baselines = Vec::new();
    let mut imports = Vec::new();
    for (base, rover) in &pairs {
        let start = later(base.start, rover.start);
        let end = earlier(base.end, rover.end);
        let mut result = Processed {
            base: base.mark.clone(),
            rover: rover.mark.clone(),
            start: start.to_string(),
            end: end.to_string(),
            file: None,
            quality: None,
            satellites: None,
            ratio: None,
            length: None,
            used: false,
            problem: None,
        };
        match run_one(
            base,
            rover,
            (start, end),
            &settings,
            &systems,
            &ephemerides,
            &nav_files,
            &antex_name,
            &antex,
            engine,
        ) {
            Err(problem) => result.problem = Some(problem),
            Ok(pos) => {
                let name = format!("{RESULTS}/{}_{}.pos", base.label, rover.label);
                store.write(&ProjectPath::new(name.as_str())?, &pos)?;
                let solution = solution(&String::from_utf8_lossy(&pos));
                result.file = Some(name.clone());
                match solution {
                    None => result.problem = Some("the engine gave no solution".into()),
                    Some(s) => {
                        result.quality = Some(quality(s.q).into());
                        result.satellites = Some(s.satellites);
                        result.ratio = Some(s.ratio);
                        result.length = s.length;
                        if s.q == 1 {
                            result.used = true;
                            imports.push(Import {
                                file: name,
                                format: Format::Rtklib,
                                // Broadcast orbits are in WGS 84.
                                frame: Some("WGS 84".into()),
                                epoch: None,
                                base: Some(base.mark.clone()),
                                rover: Some(rover.mark.clone()),
                            });
                        } else {
                            result.problem = Some(format!(
                                "not fixed ({}), so not used in the adjustment",
                                quality(s.q)
                            ));
                        }
                    }
                }
            }
        }
        baselines.push(result);
    }

    // The fixed solutions replace the last processing's in project.toml.
    let mut project: Project = loaded.project;
    project
        .imports
        .retain(|i| !i.file.starts_with(&format!("{RESULTS}/")));
    project.imports.extend(imports);
    store.write(
        &ProjectPath::new("project.toml")?,
        project.to_toml()?.as_bytes(),
    )?;
    Ok(Report { baselines, notes })
}

/// Prepares and runs one baseline, giving back its solution file.
#[allow(clippy::too_many_arguments)]
fn run_one<E: Engine>(
    base: &End,
    rover: &End,
    (start, end): (Timestamp, Timestamp),
    settings: &gnss_engine_rtklib::Settings,
    systems: &[char],
    ephemerides: &NavFile,
    nav_files: &[Vec<u8>],
    antex_name: &str,
    antex: &[u8],
    engine: &mut E,
) -> Result<Vec<u8>, String> {
    let window = (gps(start), gps(end));
    let gaps: Vec<String> = ephemerides
        .coverage(systems, window)
        .into_iter()
        .filter(|c| !c.complete())
        .map(|c| c.system.to_string())
        .collect();
    if !gaps.is_empty() {
        return Err(format!(
            "the navigation data doesn't cover {} over the overlap: fetch a mixed navigation file, or leave the constellation out in [processing]",
            gaps.join(", ")
        ));
    }
    let trim = Trim {
        window: Some(window),
        interval: None,
    };
    let obs = |e: &End| -> Result<(Vec<u8>, Option<[f64; 3]>), String> {
        let mut joined = Vec::new();
        let mut position = None;
        for (i, (bytes, patch)) in e.files.iter().enumerate() {
            let mut out = Vec::new();
            trim_obs(&bytes[..], &mut out, patch, &[], trim)
                .map_err(|err| format!("{}'s RINEX: {err}", e.label))?;
            if position.is_none() {
                position = read_obs(&out[..])
                    .ok()
                    .and_then(|r| r.header().approx_position);
            }
            if i == 0 {
                joined = out;
            } else {
                // Later files of the same station: their epochs only.
                let text = String::from_utf8_lossy(&out);
                if let Some((_, epochs)) = text.split_once("END OF HEADER\n") {
                    joined.extend_from_slice(epochs.as_bytes());
                }
            }
        }
        Ok((joined, position))
    };
    let (base_obs, base_xyz) = obs(base)?;
    let (rover_obs, rover_xyz) = obs(rover)?;
    let length = match (base_xyz, rover_xyz) {
        (Some(a), Some(b)) => libm::sqrt((0..3).map(|i| (a[i] - b[i]) * (a[i] - b[i])).sum()),
        _ => 0.0,
    };
    let config = gnss_engine_rtklib::config(
        settings,
        &Run {
            length,
            direction: Direction::Combined,
            base: Base::RinexHeader,
            orbits: Orbits::Broadcast,
            antex: antex_name.to_owned(),
            exclude: Vec::new(),
            residuals: false,
        },
    )
    .map_err(|e| e.to_string())?;
    let mut inputs = vec![
        ("run.conf".to_owned(), config.into_bytes()),
        ("rover.obs".to_owned(), rover_obs),
        ("base.obs".to_owned(), base_obs),
        (antex_name.to_owned(), antex.to_vec()),
    ];
    let mut args: Vec<String> = [
        "rnx2rtkp",
        "-k",
        "run.conf",
        "-o",
        "out.pos",
        "rover.obs",
        "base.obs",
    ]
    .map(str::to_owned)
    .to_vec();
    for (i, nav) in nav_files.iter().enumerate() {
        let name = format!("nav{i}.rnx");
        inputs.push((name.clone(), nav.clone()));
        args.push(name);
    }
    let run = engine.run(&inputs, &args, "out.pos")?;
    if run.status != 0 {
        return Err(format!("the engine failed: {}", run.stderr.trim()));
    }
    run.output
        .ok_or_else(|| format!("the engine wrote no solution: {}", run.stderr.trim()))
}

fn earlier(a: Timestamp, b: Timestamp) -> Timestamp {
    if b < a { b } else { a }
}

fn later(a: Timestamp, b: Timestamp) -> Timestamp {
    if b > a { b } else { a }
}

/// A file uncompressed, if it's gzipped.
fn gunzip(bytes: &[u8]) -> std::io::Result<Vec<u8>> {
    let mut out = Vec::new();
    gnss_rinex_io::decoded(bytes)
        .map_err(|e| std::io::Error::other(e.to_string()))?
        .read_to_end(&mut out)?;
    Ok(out)
}

/// A UTC time as GPS time, as RINEX files and their epochs are.
fn gps(t: Timestamp) -> GnssTime {
    let (y, mo, d, h, mi, s, ns) = t.epoch().to_gregorian(TimeScale::GPST);
    let seconds = format!("{s}.{ns:09}");
    GnssTime::from_fields(
        i64::from(y),
        i64::from(mo),
        i64::from(d),
        i64::from(h),
        i64::from(mi),
        &seconds,
    )
    .unwrap_or_else(|| GnssTime::from_ticks(0))
}

/// The window in a CORS file's purpose, `2025-06-15 00:55:00 to 2025-06-15
/// 05:05:00 GPS`, as UTC.
fn gps_window(text: &str) -> Option<(Timestamp, Timestamp)> {
    let (a, b) = text.trim_end_matches(" GPS").split_once(" to ")?;
    let utc = |s: &str| -> Option<Timestamp> {
        let gps =
            hifitime::Epoch::from_gregorian_str(&format!("{} GPST", s.replace(' ', "T"))).ok()?;
        Timestamp::parse(&format!(
            "{}Z",
            gps.to_time_scale(TimeScale::UTC).to_isoformat().get(..19)?
        ))
        .ok()
    };
    Some((utc(a)?, utc(b)?))
}

/// What a solution file says.
struct Solution {
    q: u32,
    satellites: u32,
    ratio: f64,
    length: Option<f64>,
}

/// The static solution in a `.pos` file (ECEF): its quality, satellites,
/// ratio, and length from the reference position in the header.
fn solution(text: &str) -> Option<Solution> {
    let line = text
        .lines()
        .rev()
        .find(|l| !l.starts_with('%') && !l.trim().is_empty())?;
    let f: Vec<&str> = line.split_whitespace().collect();
    let xyz: Vec<f64> = f.get(2..5)?.iter().filter_map(|v| v.parse().ok()).collect();
    let reference: Option<Vec<f64>> = text.lines().find_map(|l| {
        let rest = l.strip_prefix("% ref pos")?.split_once(':')?.1;
        let v: Vec<f64> = rest
            .split_whitespace()
            .filter_map(|v| v.parse().ok())
            .collect();
        (v.len() == 3).then_some(v)
    });
    let length = reference
        .filter(|_| xyz.len() == 3)
        .map(|r| libm::sqrt((0..3).map(|i| (xyz[i] - r[i]) * (xyz[i] - r[i])).sum()));
    Some(Solution {
        q: f.get(5)?.parse().ok()?,
        satellites: f.get(6)?.parse().ok()?,
        ratio: f.last()?.parse().ok()?,
        length,
    })
}

/// RTKLIB's solution quality flag, in words.
fn quality(q: u32) -> &'static str {
    match q {
        1 => "fixed",
        2 => "float",
        3 => "SBAS",
        4 => "DGPS",
        5 => "single point",
        6 => "PPP",
        _ => "unknown",
    }
}
